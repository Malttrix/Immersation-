-- 2. ARTICLES TABLE (Essays & Editorial Content)
CREATE TABLE IF NOT EXISTS public.articles (
  id TEXT PRIMARY KEY,
  title JSONB NOT NULL,
  excerpt JSONB,
  content JSONB,
  category JSONB,
  date JSONB,
  readTime JSONB,
  pillar TEXT,
  featured BOOLEAN DEFAULT FALSE,
  cover TEXT,
  audio TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. NEWSLETTERS TABLE (Campaign Issues)
CREATE TABLE IF NOT EXISTS public.newsletters (
  id TEXT PRIMARY KEY,
  title JSONB,
  subject JSONB,
  excerpt JSONB,
  content JSONB,
  category JSONB,
  date JSONB,
  readTime JSONB,
  pillar TEXT,
  status TEXT DEFAULT 'Draft',
  emailSubject TEXT,
  sendfoxCampaignId TEXT,
  sentAt TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. NEWSLETTER SUBSCRIPTIONS TABLE
CREATE TABLE IF NOT EXISTS public.newsletter_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  tags JSONB,
  subscribed_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. PURCHASES TABLE (Orders & Billing Records)
CREATE TABLE IF NOT EXISTS public.purchases (
  id TEXT PRIMARY KEY,
  transaction_id TEXT,
  email TEXT,
  item TEXT,
  amount NUMERIC DEFAULT 0,
  date TEXT,
  status TEXT DEFAULT 'Successful',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. COUPONS TABLE
CREATE TABLE IF NOT EXISTS public.coupons (
  code TEXT PRIMARY KEY,
  type TEXT DEFAULT 'percent',
  value NUMERIC DEFAULT 0,
  appliesTo TEXT DEFAULT 'all',
  limit_count NUMERIC DEFAULT 100,
  used NUMERIC DEFAULT 0,
  expires TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. ARTICLE COMMENTS TABLE
CREATE TABLE IF NOT EXISTS public.article_comments (
  id TEXT PRIMARY KEY,
  article_id TEXT,
  author TEXT,
  content TEXT,
  likes NUMERIC DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 8. COMMENT LIKES TABLE
CREATE TABLE IF NOT EXISTS public.comment_likes (
  id TEXT PRIMARY KEY,
  comment_id TEXT,
  user_id TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

